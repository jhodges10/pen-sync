/**
 * Write the library reference agents read before designing in Pencil
 * (`pen-sync.config.json` → library): every synced component by level with
 * its Pencil component names, variant keys, source and slots, then the token
 * variables to bind to. It is read from the .pen file itself, headless, so it
 * lists exactly what a designer can place.
 *
 *   node $DS/pen-library.mjs           # write it
 *   node $DS/pen-library.mjs --check   # exit 1 when it no longer matches the file
 */
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";

import { config, registryPath, repo } from "./config.mjs";
import { call, openShell, parseResult } from "./pen-sync.mjs";
import { isMain } from "./main.mjs";

/**
 * Runs in Pencil: each section's reusable components as
 * `{ components: { id: [[key, name, nodeId]] }, slots: { id: { layer: [component names] } } }`.
 */
export const LIBRARY = (prefix) =>
  `const ck=(n)=>{const x=/\\nVariant: (.*)$/.exec(n.context||"");return x?(x[1]==="(default)"?"":x[1]):null};const out={components:{},slots:{}};const names={};` +
  `Get((n,c)=>{if(n.reusable)names[n.id]=n.name;if(!n.reusable&&!n.slot)return undefined;let id=null;` +
  `for(let p=c.parentCtx;!id&&p;p=p.parentCtx){const m=p.node.metadata;if(m&&m.type===${JSON.stringify(`${prefix}-section`)})id=m.id}` +
  `if(!id)return undefined;if(n.slot){(out.slots[id]??={})[n.name]=n.slot;return undefined}const k=ck(n);if(k!==null)(out.components[id]??=[]).push([k,n.name,n.id]);return undefined});` +
  `for(const s of Object.values(out.slots))for(const l of Object.keys(s))s[l]=[...new Set(s[l].map((i)=>names[i]||i))];` +
  `Print(JSON.stringify(out))`;

const LEVELS = config.boards?.levels?.map(([level]) => level) ?? ["atom", "molecule", "organism", "template"];

/** The reference as Markdown: components by level, then token families. */
export function libraryMarkdown({ registry, inventory, slots = {}, tokens, pen, prefix }) {
  const lines = [
    "# Design-system library",
    "",
    `Generated by the pen-sync plugin's pen-library.mjs from \`${pen}\`. Do not edit; re-run it after a sync.`,
    "",
    "Build screens from these components: insert a `ref` to the component (by its node id) and",
    "override layers by name (`descendants: { Label: { content: \"Save\" } }`), never a copy or a",
    "hand-drawn lookalike. Bind every color, radius and spacing to the variables listed below.",
    `Each library component's \`context\` names its JSX, source and story; its section carries`,
    `\`${prefix}-section\` metadata with the registry id.`,
    "",
  ];
  const slotsOf = (c) => Object.entries(slots[c.id] ?? {});
  for (const level of LEVELS) {
    const components = registry.components.filter((c) => c.level === level && inventory[c.id]);
    if (!components.length) continue;
    lines.push(`## ${level.charAt(0).toUpperCase()}${level.slice(1)}s`, "");
    for (const c of components) {
      const variants = inventory[c.id];
      lines.push(`### ${c.name} — \`${c.id}\``, "", `Source \`${c.file}\`.`, "");
      lines.push("| Pencil component | Variant key | Node |", "| --- | --- | --- |");
      for (const [key, name, node] of variants)
        lines.push(`| ${name} | \`${key || "(default)"}\` | \`${node}\` |`);
      const slots = slotsOf(c);
      if (slots.length) {
        lines.push("", "Slots (empty frames to fill):");
        for (const [slot, names] of slots) lines.push(`- \`${slot}\`: ${names.join(", ")}`);
      }
      lines.push("");
    }
  }
  const missing = registry.components.filter((c) => !inventory[c.id]).map((c) => c.id);
  if (missing.length)
    lines.push(`Not in the file yet: ${missing.join(", ")}.`, "");
  // Token families: `--color-status-blue-soft` files under `--color-status`.
  const families = new Map();
  for (const name of Object.keys(tokens.color ?? {})) {
    const family = name.split("-").slice(0, 4).join("-").replace(/-[^-]*$/, "") || name;
    families.set(family, [...(families.get(family) ?? []), name]);
  }
  lines.push("## Color variables", "");
  for (const [family, names] of [...families].sort())
    lines.push(`- **${family}**: ${names.map((n) => `\`${n}\``).join(", ")}`);
  const numbers = Object.keys(tokens.dimension ?? {});
  if (numbers.length) lines.push("", "## Size variables", "", numbers.map((n) => `\`${n}\``).join(", "));
  return `${lines.join("\n")}\n`;
}

if (isMain(import.meta.url)) {
  const pen = join(repo, config.pen);
  // Read a copy headless: the reference describes the saved file.
  const copy = join(mkdtempSync(join(tmpdir(), "pen-library-")), "library.pen");
  copyFileSync(pen, copy);
  const shell = openShell(["-i", copy, "-o", copy]);
  await shell.ready;
  let inventory;
  let slots;
  try {
    const result = parseResult(
      await shell.send(call("execute", { description: "List the library", input: LIBRARY(config.metadataPrefix) })),
    );
    if (!result.ok) throw new Error(result.text);
    ({ components: inventory, slots } = JSON.parse(
      result.printed.split("\n").find((l) => l.startsWith("{")),
    ));
  } finally {
    await shell.close();
  }
  const registry = JSON.parse(readFileSync(registryPath, "utf8"));
  const tokens = JSON.parse(readFileSync(join(repo, config.tokens), "utf8"));
  const text = libraryMarkdown({
    registry,
    inventory,
    slots,
    tokens,
    pen: config.pen,
    prefix: config.metadataPrefix,
  });
  const out = join(repo, config.library);
  if (process.argv.includes("--check")) {
    const current = existsSync(out) ? readFileSync(out, "utf8") : "";
    if (current !== text) {
      console.error(`${config.library} is stale: re-run pen-library.mjs and commit it.`);
      process.exit(1);
    }
    console.error(`✓ ${config.library} matches ${config.pen}`);
  } else {
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, text);
    console.error(`Wrote ${config.library} (${Object.keys(inventory).length} components).`);
  }
}
