/**
 * Extract every registry component's variant axes from its TypeScript props,
 * through a docgen (`pen-sync.config.json` → docgen, or the bundled TypeScript one),
 * into `packages/components/src/design-system/variants.json`. The matrix stories
 * render from it, and the registry test checks each component's `matrix`
 * against it, so a new cva variant can't land without someone deciding whether
 * Pencil mirrors it.
 *
 *   node $DS/variants.mjs           # write the file
 *   node $DS/variants.mjs --check   # exit 1 if it is stale
 *
 * Stories only show the combinations someone thought to write; the prop types
 * are total. An axis is a prop declared inside the component package (a cva
 * variant or a prop the component adds) whose type is a union of literals, so
 * `variant`, `size` and Checkbox's `checked`, but not React's 280 DOM props. A
 * few inherited props that change how a control looks (`disabled`,
 * `aria-invalid`…) are kept as states. Defaults aren't in the types; a matrix
 * row holds an axis at its default by leaving the prop out.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { config, packageRoot, registryPath, repo } from "./config.mjs";
import { localImports } from "./source-hash.mjs";

const REGISTRY = registryPath;
const OUTPUT = join(packageRoot, config.variants);

/**
 * Inherited props worth mirroring, each with the selector a component's
 * classes use to style it. Every control inherits `aria-invalid` from React's
 * DOM types, so a state only counts when the component's source styles it.
 */
export const STATE_PROPS = {
  disabled: /\bdisabled:|data-disabled|\[disabled\]/,
  "aria-invalid": /aria-invalid:|data-invalid/,
  indeterminate: /indeterminate/,
  readOnly: /read-only:|data-readonly|readonly:/i,
  required: /required:|data-required/,
  // Inherited from Base UI's Switch, Toggle and Radio roots, which stamp the attribute.
  checked: /data-checked|data-\[state=checked\]/,
  pressed: /data-pressed|aria-pressed:/,
};

/**
 * Sort a prop list into axes and states. `props` entries are
 * `{ name, own, values }`: `own` is whether a declaration sits in the package,
 * `values` the literal members of its type, or null when it isn't a literal
 * union (a callback, a node, a string). `source` is the component's code, the
 * file plus its package-local imports.
 */
export function classifyProps(props, source) {
  const axes = {};
  const states = [];
  for (const { name, own, values } of props) {
    if (own && values && values.length > 1) axes[name] = values;
    else if (!own && STATE_PROPS[name]?.test(source)) states.push(name);
  }
  return {
    axes: Object.fromEntries(
      Object.entries(axes).sort(([a], [b]) => a.localeCompare(b)),
    ),
    states: Object.keys(STATE_PROPS).filter((name) => states.includes(name)),
  };
}

/** Axes and states of each registry component, read through the configured docgen (or the bundled one). */
export async function extractVariants(components, root = packageRoot) {
  const { createDocgenSession } = await import(
    config.docgen
      ? pathToFileURL(join(repo, config.docgen)).href
      : "./docgen.mjs"
  );
  const session = createDocgenSession({ cwd: root });
  try {
    const described = session.describe(
      components.map(({ name, export: exported = name, file }) => ({
        dir: dirname(join(root, file)),
        specifier: `./${basename(file).replace(/\.tsx?$/, "")}`,
        exportName: exported,
      })),
      { inherited: Object.keys(STATE_PROPS) },
    );
    // An axis must be declared in this package, not merely outside
    // node_modules. Declaration paths come back lower-cased on
    // case-insensitive disks.
    const inPackage = (path) => {
      const lower = path.toLowerCase();
      return (
        lower.startsWith(`${root.toLowerCase()}/`) &&
        !lower.includes("/node_modules/")
      );
    };
    const out = {};
    components.forEach(({ id, file }, i) => {
      const component = described[i];
      if (!component || component.error) {
        throw new Error(`${id}: could not resolve the props of its export`);
      }
      const props = component.props.map((prop) => ({
        name: prop.name,
        own: prop.declarations.some(inPackage),
        values: prop.values,
      }));
      const source = [file, ...localImports(file, root)]
        .map((path) => readFileSync(join(root, path), "utf8"))
        .join("\n");
      out[id] = classifyProps(props, source);
    });
    return out;
  } finally {
    session.close();
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const registry = JSON.parse(readFileSync(REGISTRY, "utf8"));
  const document = {
    $comment:
      "Generated by the pen-sync plugin's variants.mjs from the registry components' prop types. Do not edit.",
    components: await extractVariants(registry.components),
  };
  const text = `${JSON.stringify(document, null, 2)}\n`;
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(OUTPUT, "utf8");
    } catch {}
    if (current !== text) {
      console.error(
        `${join(config.package, config.variants)} is stale: re-run variants.mjs and commit it.`,
      );
      process.exit(1);
    }
  } else {
    writeFileSync(OUTPUT, text);
    const count = Object.values(document.components).filter(
      (c) => Object.keys(c.axes).length,
    ).length;
    console.error(
      `${Object.keys(document.components).length} components, ${count} with variant axes`,
    );
  }
}
